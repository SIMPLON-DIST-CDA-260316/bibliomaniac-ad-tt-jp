export function getBookById(id: string): Book | undefined {
  return mockBooks.find((book) => book.id === id);
}

export function getBooksByCategories(
  categories: string[],
  excludeId: string,
): Book[] {
  return mockBooks.filter(
    (book) =>
      book.id !== excludeId &&
      book.categories.some((c) => categories.includes(c)),
  );
}
